import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import supportedLocales from "../../src/lib/supported-locales.json" with { type: "json" };

const workerDir = fileURLToPath(new URL("..", import.meta.url));
const defaultContentDir = path.resolve(workerDir, "..", "content");
export const outputFile = path.join(workerDir, "src", "published-slugs.js");

export function generatePostSlugs(contentDir = defaultContentDir) {
  const slugs = new Set();
  const contentLocales = new Set(fs.readdirSync(contentDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory()).map((entry) => entry.name));
  // Share the site's actual route locales; extra content directories are not published.
  for (const locale of Object.keys(supportedLocales)) {
    if (!contentLocales.has(locale)) continue;
    const postsDir = path.join(contentDir, locale, "posts");
    if (!fs.existsSync(postsDir)) continue;
    for (const entry of fs.readdirSync(postsDir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith(".mdx")) continue;
      const slug = entry.name.slice(0, -4);
      // Match src/lib/posts.ts: draft is Boolean(data.draft ?? false).
      const { data } = matter(fs.readFileSync(path.join(postsDir, entry.name), "utf8"));
      if (Boolean(data.draft ?? false)) continue;
      if (!/^[a-z0-9][a-z0-9-]{0,127}$/i.test(slug)) {
        throw new Error(`Published post has an unsupported view-counter slug: ${entry.name}`);
      }
      slugs.add(slug);
    }
  }
  if (slugs.size === 0) throw new Error("No published posts found; refusing to generate an empty allowlist");
  return `// Generated by scripts/generate-post-slugs.mjs. Do not edit by hand.\nexport const publishedSlugs = Object.freeze(${JSON.stringify([...slugs].sort(), null, 2)});\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = generatePostSlugs();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(outputFile) || fs.readFileSync(outputFile, "utf8") !== generated) {
      console.error("Published post allowlist is stale. Run pnpm --dir views-worker allowlist:generate and include the result.");
      process.exitCode = 1;
    }
  } else if (!fs.existsSync(outputFile) || fs.readFileSync(outputFile, "utf8") !== generated) {
    fs.writeFileSync(outputFile, generated);
  }
}
